export const useTranslation = () => {
    const { language } = useAuth();
    // Default to English if language not found or not set
    const currentLanguage = (language && translations[language]) ? language : 'English';

    const t = (key: string) => {
        return translations[currentLanguage]?.[key] || translations['English'][key] || key;
    };

    return t;
};
